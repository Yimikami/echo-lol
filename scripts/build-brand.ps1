# Regenerate Echo's raster, Windows and WPF brand assets from the selected SVG.
# Run on Windows: pwsh -STA ./scripts/build-brand.ps1
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName PresentationCore,WindowsBase
$root = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$brand = Join-Path $root 'assets/brand'
[xml]$svg = Get-Content -LiteralPath (Join-Path $brand 'echo-emblem.svg') -Raw
if ($svg.svg.viewBox -ne '0 0 256 256') { throw 'Expected the 256 x 256 Echo brand canvas.' }
$paths = @($svg.svg.path | ForEach-Object { [string]$_.d })
if ($paths.Count -eq 0) { throw 'The brand source has no paths.' }
$ink = [string]$svg.svg.fill
$utf8 = [Text.UTF8Encoding]::new($false)

function Render-Mark([int]$size, [bool]$tile) {
    $visual = [Windows.Media.DrawingVisual]::new()
    $drawing = $visual.RenderOpen()
    $drawing.PushTransform([Windows.Media.ScaleTransform]::new($size / 256.0, $size / 256.0))
    if ($tile) {
        $back = [Windows.Media.SolidColorBrush]::new([Windows.Media.ColorConverter]::ConvertFromString('#15181A'))
        $back.Freeze()
        $drawing.DrawRoundedRectangle($back, $null, [Windows.Rect]::new(0, 0, 256, 256), 48, 48)
    }
    $brush = [Windows.Media.SolidColorBrush]::new([Windows.Media.ColorConverter]::ConvertFromString($ink))
    $brush.Freeze()
    foreach ($path in $paths) {
        $geometry = [Windows.Media.Geometry]::Parse('F0 ' + $path)
        $drawing.DrawGeometry($brush, $null, $geometry)
    }
    $drawing.Pop()
    $drawing.Close()
    $bitmap = [Windows.Media.Imaging.RenderTargetBitmap]::new($size, $size, 96, 96, [Windows.Media.PixelFormats]::Pbgra32)
    $bitmap.Render($visual)
    $encoder = [Windows.Media.Imaging.PngBitmapEncoder]::new()
    $encoder.Frames.Add([Windows.Media.Imaging.BitmapFrame]::Create($bitmap))
    $stream = [IO.MemoryStream]::new()
    try {
        $encoder.Save($stream)
        return ,$stream.ToArray()
    } finally { $stream.Dispose() }
}

[IO.File]::WriteAllBytes((Join-Path $brand 'echo-emblem.png'), (Render-Mark 512 $false))
$light = (Get-Content -LiteralPath (Join-Path $brand 'echo-emblem.svg') -Raw).Replace('fill="' + $ink + '"', 'fill="#172305"')
[IO.File]::WriteAllText((Join-Path $brand 'echo-emblem-light.svg'), $light, $utf8)

# Individual Windows/DPI sizes avoid scaling a single large image down for the tray.
$sizes = @(16,20,24,32,40,48,64,128,256)
$frames = @($sizes | ForEach-Object { ,(Render-Mark $_ $true) })
$stream = [IO.MemoryStream]::new()
$writer = [IO.BinaryWriter]::new($stream)
try {
    $writer.Write([uint16]0); $writer.Write([uint16]1); $writer.Write([uint16]$sizes.Count)
    $offset = 6 + 16 * $sizes.Count
    for ($i = 0; $i -lt $sizes.Count; $i++) {
        $dimension = if ($sizes[$i] -eq 256) { 0 } else { $sizes[$i] }
        $writer.Write([byte]$dimension); $writer.Write([byte]$dimension)
        $writer.Write([byte]0); $writer.Write([byte]0)
        $writer.Write([uint16]1); $writer.Write([uint16]32)
        $writer.Write([uint32]$frames[$i].Length); $writer.Write([uint32]$offset)
        $offset += $frames[$i].Length
    }
    foreach ($frame in $frames) { $writer.Write([byte[]]$frame) }
    $writer.Flush()
    [IO.File]::WriteAllBytes((Join-Path $brand 'echo.ico'), $stream.ToArray())
} finally { $writer.Dispose(); $stream.Dispose() }

# Use the same geometry in WPF without adding an SVG runtime dependency.
$geometry = @('<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation" xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">',
    '  <!-- Generated by scripts/build-brand.ps1 from assets/brand/echo-emblem.svg. -->',
    '  <GeometryGroup x:Key="EchoBrandGeometry" FillRule="Nonzero">')
$geometry += $paths | ForEach-Object { '    <PathGeometry FillRule="EvenOdd" Figures="' + [Security.SecurityElement]::Escape($_) + '"/>' }
$geometry += @('  </GeometryGroup>', '</ResourceDictionary>')
[IO.File]::WriteAllText((Join-Path $root 'src/Echo.App/Assets/Brand.xaml'), ($geometry -join [char]10) + [char]10, $utf8)
Write-Output "Generated Fold PNG, light SVG, 9-size Windows icon and native geometry."
